algo = input("digite algo: ")
print(f"o tipo primitivo desse valor e {type(algo)}")
print(f"tem espacos? {algo.isspace()}")
print(f"e um numero? {algo.isalnum()}")
print(f"e alfabetico? {algo.isalpha()}")
print(f"esta em maiusculo? {algo.isupper()}")
print(f"esta em minusculo? {algo.islower()}")
print(f"esta em minusculo? {algo.istitle()}")


